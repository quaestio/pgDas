"""Editing rows in the data grid: change cells, add rows and delete rows, saved together as ONE reviewed, recorded change.

The grid sends what the person did (the key of each row, the old and new text of each changed cell, the new rows, the rows to
delete). Nothing is trusted from it: the table must have a primary key, every old value must still be what the database holds,
and the whole batch runs in one transaction that the preview always rolls back. The audit record keeps the old and new rows, so
a staff user can undo the batch (undo()) as long as nobody changed those rows again.

  edits    [{"key": {pk column: text}, "old": {column: text|null}, "set": {column: text|null}}]    primary key cells are not editable
  inserts  [{column: text|null}]                                                                    a column left out gets its default
  deletes  [{"key": {pk column: text}}]
"""
import hashlib
import json

from django.conf import settings
from django.utils import timezone
from psycopg import sql
from psycopg.types.json import Jsonb

from audit.models import record

from . import changes, pg, writes
from .pg import PgError

MAX_OPERATIONS = 5000        # also the most rows one CSV import can add (static/table_io.js)
SHOWN_LINES = 200


def _table(schema, table):
    return sql.SQL("{}.{}").format(sql.Identifier(schema), sql.Identifier(table))


def _text(value):
    return value if value is None or isinstance(value, str) else str(value)


def _literal(value):
    return "NULL" if value is None else "'" + str(value).replace("'", "''") + "'"


def _ident(name):
    return '"' + name.replace('"', '""') + '"'


def _key_where(pk, key):
    if sorted(key) != sorted(pk):
        raise PgError("A row was sent without its primary key. Reload the table and try again.")
    return sql.SQL(" AND ").join(sql.SQL("{} = {}").format(sql.Identifier(c), sql.Placeholder()) for c in pk), [_text(key[c]) for c in pk]


def _clean(data):
    """The request, checked for shape. Returns (schema, table, edits, inserts, deletes)."""
    schema, table = str(data.get("schema") or ""), str(data.get("table") or "")
    edits, inserts, deletes = data.get("edits") or [], data.get("inserts") or [], data.get("deletes") or []
    if not schema or not table:
        raise PgError("That request was not understood.")
    if not all(isinstance(group, list) for group in (edits, inserts, deletes)):
        raise PgError("That request was not understood.")
    if not (edits or inserts or deletes):
        raise PgError("Nothing has been changed.")
    if len(edits) + len(inserts) + len(deletes) > MAX_OPERATIONS:
        raise PgError(f"Save at most {MAX_OPERATIONS:,} changes at a time.")
    for edit in edits:
        if not isinstance(edit, dict) or not isinstance(edit.get("key"), dict) or not isinstance(edit.get("set"), dict) or not edit["set"]:
            raise PgError("That request was not understood.")
    if not all(isinstance(row, dict) for row in inserts) or not all(isinstance(d, dict) and isinstance(d.get("key"), dict) for d in deletes):
        raise PgError("That request was not understood.")
    return schema, table, edits, inserts, deletes


def _apply(conn, data):
    """Run the whole batch in the open transaction. Returns what happened: the old and new rows and readable lines."""
    schema, table, edits, inserts, deletes = _clean(data)
    changes._resolve_table(conn, f"{_ident(schema)}.{_ident(table)}")
    pk = changes._primary_key(conn, schema, table)
    if not pk:
        raise PgError("This table has no primary key, so its rows cannot be edited here.")
    columns = {c["name"]: c for c in pg.table_columns(conn, schema, table)}
    locked = [name for name, c in columns.items() if c["generated"] or c["identity"] == "a"]
    conn.execute(sql.SQL("LOCK TABLE {} IN SHARE ROW EXCLUSIVE MODE").format(_table(schema, table)))
    old_rows, new_rows, lines, statements = [], [], [], []
    ident_list = lambda names: ", ".join(_ident(n) for n in names)

    for edit in edits:
        names = list(edit["set"])
        for name in names:
            if name not in columns:
                raise PgError(f"Column {name} does not exist.")
            if name in pk:
                raise PgError(f"{name} is part of the primary key and cannot be edited in the grid.")
            if name in locked:
                raise PgError(f"{name} is generated by the database and cannot be edited.")
        where, key_params = _key_where(pk, edit["key"])
        current = conn.execute(sql.SQL("SELECT to_jsonb(t), {} FROM {} t WHERE ").format(
            sql.SQL(", ").join(sql.SQL("t.{}::text").format(sql.Identifier(n)) for n in names), _table(schema, table)) + where, key_params).fetchone()
        key_text = ", ".join(f"{c}={edit['key'][c]}" for c in pk)
        if current is None:
            raise PgError(f"The row {key_text} no longer exists. Nothing was changed; reload the table.")
        for name, shown in zip(names, current[1:]):
            if name in (edit.get("old") or {}) and edit["old"][name] != shown:
                raise PgError(f"The row {key_text} was changed by someone else ({name} is now {_literal(shown)}). Nothing was changed; reload the table.")
        assign = sql.SQL(", ").join(sql.SQL("{} = {}").format(sql.Identifier(n), sql.Placeholder()) for n in names)
        updated = changes._run(conn, sql.SQL("UPDATE {} t SET {} WHERE ").format(_table(schema, table), assign) + where + sql.SQL(" RETURNING to_jsonb(t)"), [_text(edit["set"][n]) for n in names] + key_params)
        rows = updated.fetchall()
        if len(rows) != 1:
            raise PgError(f"The row {key_text} could not be updated. Nothing was changed.")
        old_rows.append(current[0])
        new_rows.append(rows[0][0])
        shown_changes = ", ".join(f"{n}: {_literal(old)} → {_literal(edit['set'][n])}" for n, old in zip(names, current[1:]))
        lines.append(f"~ change row {key_text}: {shown_changes}")
        statements.append(f"UPDATE {_ident(schema)}.{_ident(table)} SET " + ", ".join(f"{_ident(n)} = {_literal(edit['set'][n])}" for n in names)
                          + " WHERE " + " AND ".join(f"{_ident(c)} = {_literal(edit['key'][c])}" for c in pk))

    inserted = []
    for row in inserts:
        names = list(row)
        for name in names:
            if name not in columns:
                raise PgError(f"Column {name} does not exist.")
            if name in locked:
                raise PgError(f"{name} is generated by the database and cannot be given a value.")
        if names:
            statement = sql.SQL("INSERT INTO {} AS t ({}) VALUES ({}) RETURNING to_jsonb(t)").format(
                _table(schema, table), sql.SQL(", ").join(sql.Identifier(n) for n in names), sql.SQL(", ").join(sql.Placeholder() for _ in names))
        else:
            statement = sql.SQL("INSERT INTO {} AS t DEFAULT VALUES RETURNING to_jsonb(t)").format(_table(schema, table))
        made = changes._run(conn, statement, [_text(row[n]) for n in names]).fetchone()[0]
        inserted.append(made)
        lines.append("+ add row " + (", ".join(f"{n}={_literal(row[n])}" for n in names) if names else "with all defaults"))
        statements.append(f"INSERT INTO {_ident(schema)}.{_ident(table)} " + (f"({ident_list(names)}) VALUES ({', '.join(_literal(row[n]) for n in names)})"
                                                                              if names else "DEFAULT VALUES"))

    deleted = []
    for item in deletes:
        where, key_params = _key_where(pk, item["key"])
        gone = changes._run(conn, sql.SQL("DELETE FROM {} t WHERE ").format(_table(schema, table)) + where + sql.SQL(" RETURNING to_jsonb(t)"), key_params).fetchall()
        key_text = ", ".join(f"{c}={item['key'][c]}" for c in pk)
        if len(gone) != 1:
            raise PgError(f"The row {key_text} no longer exists. Nothing was changed; reload the table.")
        deleted.append(gone[0][0])
        lines.append(f"− delete row {key_text}")
        statements.append(f"DELETE FROM {_ident(schema)}.{_ident(table)} WHERE " + " AND ".join(f"{_ident(c)} = {_literal(item['key'][c])}" for c in pk))

    changed_columns = [name for name in columns if name not in locked and any(old.get(name) != new.get(name) for old, new in zip(old_rows, new_rows))]
    return {"schema": schema, "table": table, "pk": pk, "order": list(columns), "old": old_rows, "new": new_rows, "inserted": inserted, "deleted": deleted,
            "columns": changed_columns, "lines": lines, "statements": statements,
            "digest": hashlib.sha256(json.dumps([old_rows, deleted], sort_keys=True, default=str).encode()).hexdigest()}


def preview(server, database, data):
    with pg.connect_rw(server, database or None) as conn:
        result = _apply(conn, data)
        conn.rollback()
    updates, adds, removes = len(result["old"]), len(result["inserted"]), len(result["deleted"])
    parts = [f"{n:,} {word}" for n, word in ((updates, "changed"), (adds, "added"), (removes, "deleted")) if n]
    total = updates + adds + removes
    shown = result["lines"][:SHOWN_LINES]
    notes = []
    if len(result["lines"]) > SHOWN_LINES:
        notes.append({"text": f"Showing the first {SHOWN_LINES} of {len(result['lines']):,} changes. All of them are saved in the audit log.", "bad": False})
    notes.append({"text": "Triggers and cascades on this table can change other rows; those changes are not saved in the audit log.", "bad": False})
    return {"kind": "rows", "statement": ";\n".join(result["statements"][:SHOWN_LINES]) + (";" if result["statements"] else ""),
            "schema": result["schema"], "table": result["table"], "count": total,
            "objects": [{"name": line, "text": line, "rows": None, "cascade": False} for line in shown], "notes": notes,
            "title": f"SAVE {total:,} CHANGE{'' if total == 1 else 'S'}?", "headline": f"{total:,}",
            "headline_label": ", ".join(parts) + f" in {result['schema']}.{result['table']}.",
            "warning": ("The rows to delete are removed for good, but PGDAS saves the old and new rows in the audit log, where a staff user can undo "
                        "this whole save (as long as those rows have not been changed again)." if removes else
                        "There is no rollback, but PGDAS saves the old and new rows in the audit log, where a staff user can undo this whole save "
                        "(as long as those rows have not been changed again)."),
            "confirm_word": writes.CONFIRM_WORD if removes else None, "button": f"Save {total:,} change{'' if total == 1 else 's'}",
            "side_effects": [], "columns": [], "sample": [], "has_where": True,
            "fingerprint": {"updates": updates, "inserts": adds, "deletes": removes, "digest": result["digest"]}}


def execute(server, database, data, fingerprint, confirm, user):
    with pg.connect_rw(server, database or None) as conn:
        result = _apply(conn, data)
        expected = (result["digest"], len(result["old"]), len(result["inserted"]), len(result["deleted"]))
        if expected != (fingerprint.get("digest"), fingerprint.get("updates"), fingerprint.get("inserts"), fingerprint.get("deletes")):
            raise changes._changed_since("the rows are not what you were shown.")
        if result["deleted"] and confirm != writes.CONFIRM_WORD:
            raise PgError(f"Type {writes.CONFIRM_WORD} in capital letters to confirm.")
        total = len(result["old"]) + len(result["inserted"]) + len(result["deleted"])
        payload = {"kind": "rows", "database": changes._current_database(conn), "schema": result["schema"], "table": result["table"], "count": total,
                   "pk": result["pk"], "columns": result["columns"], "order": result["order"], "old": result["old"], "new": result["new"],
                   "inserted": result["inserted"], "deleted": result["deleted"]}
        detail = ";\n".join(result["statements"])
        entry = changes._commit_after_recording(conn, server, user, "rows.edit", detail, total, payload, "changed")
    return {"count": total, "entry_id": entry.pk,
            "message": f"Saved {total:,} change{'' if total == 1 else 's'} in {result['schema']}.{result['table']}. "
                       f"Recorded in the audit log as entry #{entry.pk}, where it can be undone."}


def undo(entry, user):
    """Put a saved batch back: delete the added rows, restore the changed ones, re-insert the deleted ones. All or nothing, once,
    and only if the rows still look as the batch left them."""
    payload = entry.payload or {}
    if payload.get("kind") != "rows" or not entry.ok:
        raise PgError("This audit entry is not a saved row edit.")
    if entry.restored_at is not None:
        raise PgError("This change was already undone.")
    server = entry.server
    if server is None:
        raise PgError("The server this was changed on is no longer saved in PGDAS.")
    schema, table, pk = payload["schema"], payload["table"], payload["pk"]
    new, inserted, deleted, old = payload.get("new") or [], payload.get("inserted") or [], payload.get("deleted") or [], payload.get("old") or []
    with pg.connect_rw(server, payload["database"]) as conn:
        changes._resolve_table(conn, f"{_ident(schema)}.{_ident(table)}")
        if changes._primary_key(conn, schema, table) != pk:
            raise PgError("The primary key of the table is not what it was, so the rows cannot be matched. Nothing was changed.")
        conn.execute(sql.SQL("LOCK TABLE {} IN SHARE ROW EXCLUSIVE MODE").format(_table(schema, table)))
        t = sql.Identifier(schema), sql.Identifier(table)

        def matching(rows, same):
            query = sql.SQL("SELECT count(*) FROM {s}.{t} t JOIN jsonb_populate_recordset(NULL::{s}.{t}, %s) n ON {match}" + (" WHERE to_jsonb(t) = to_jsonb(n)" if same else "")
                            ).format(s=t[0], t=t[1], match=changes._key_match(pk, "t", "n"))
            return conn.execute(query, (Jsonb(rows),)).fetchone()[0]

        if (new and matching(new, True) != len(new)) or (inserted and matching(inserted, True) != len(inserted)):
            raise PgError("Some of these rows were changed or deleted again after this save, so nothing was undone. Undoing now would overwrite newer values.")
        if deleted and matching(deleted, False):
            raise PgError("Some deleted rows were added back (or their keys reused) after this save, so nothing was undone.")
        if inserted:
            conn.execute(sql.SQL("DELETE FROM {s}.{t} t USING jsonb_populate_recordset(NULL::{s}.{t}, %s) n WHERE {match}").format(
                s=t[0], t=t[1], match=changes._key_match(pk, "t", "n")), (Jsonb(inserted),))
        if old and payload.get("columns"):
            assign = sql.SQL(", ").join(sql.SQL("{} = o.{}").format(sql.Identifier(c), sql.Identifier(c)) for c in payload["columns"])
            done = conn.execute(sql.SQL("UPDATE {s}.{t} t SET {assign} FROM jsonb_populate_recordset(NULL::{s}.{t}, %s) o WHERE {match}").format(
                s=t[0], t=t[1], assign=assign, match=changes._key_match(pk, "t", "o")), (Jsonb(old),)).rowcount
            if done != len(old):
                raise PgError(f"Only {done} of {len(old)} changed rows could be put back, so nothing was changed.")
        if deleted:
            columns = [c["name"] for c in pg.table_columns(conn, schema, table) if not c["generated"]]
            names = sql.SQL(", ").join(sql.Identifier(c) for c in columns)
            override = sql.SQL(" OVERRIDING SYSTEM VALUE") if any(c["identity"] for c in pg.table_columns(conn, schema, table)) else sql.SQL("")
            conn.execute(sql.SQL("INSERT INTO {s}.{t} ({names}){override} SELECT {names} FROM jsonb_populate_recordset(NULL::{s}.{t}, %s)").format(
                s=t[0], t=t[1], names=names, override=override), (Jsonb(deleted),))
        count = len(new) + len(inserted) + len(deleted)
        entry.restored_at, entry.restored_by = timezone.now(), user.get_username()
        entry.save(update_fields=["restored_at", "restored_by"])
        undo_entry = record(user, "update.undo", server, f"Undid a saved row edit ({count} changes) in {schema}.{table} (audit entry #{entry.pk})",
                            rows=count, payload={"kind": "undo", "undone_entry": entry.pk, "database": payload["database"], "schema": schema,
                                                 "table": table, "count": count})
        try:
            conn.commit()
        except Exception:
            entry.restored_at, entry.restored_by = None, ""
            entry.save(update_fields=["restored_at", "restored_by"])
            undo_entry.delete()
            raise PgError("The database did not accept the undo, so nothing was changed.")
    return {"count": count, "schema": schema, "table": table}
