// The editable data grid (Data tab of a table with a primary key): change cells, add rows, tick rows to delete, then Save once.
// Changes are only collected on the page. Save sends them as ONE batch to the review popup (static/review.js), which lists every
// change; the batch is saved in one transaction and recorded in the audit log, from where it can be undone (explorer/row_edits.py).
// Values are put into the page as text, never as HTML.
(function () {
  if (!window.pgdasReview) return;
  var toastEl = document.getElementById("pgToast"), toastTimer = null;

  function toast(message) {
    if (!toastEl) return;
    toastEl.textContent = message; toastEl.className = "toast"; toastEl.hidden = false;
    clearTimeout(toastTimer);
    toastTimer = setTimeout(function () { toastEl.hidden = true; }, 6000);
  }

  function el(tag, attrs, children) {
    var node = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (key) {
      if (key === "text") node.textContent = attrs[key]; else if (key === "class") node.className = attrs[key]; else node.setAttribute(key, attrs[key]);
    });
    (children || []).forEach(function (child) { node.appendChild(child); });
    return node;
  }

  function gridOf(node) { return node.closest("[data-grid]"); }
  function info(grid) { return JSON.parse(grid.getAttribute("data-grid")); }

  // pending changes live on the DOM: a changed cell has data-new (its new text; data-new-null for NULL), a row to delete has the class "deleting",
  // a row to add is a tr.new-row.
  function cellValue(td) { return td.hasAttribute("data-new-null") ? null : td.getAttribute("data-new"); }
  function pendingCells(grid) { return grid.querySelectorAll("td[data-new], td[data-new-null]"); }

  function count(grid) {
    var rows = {}, n = 0;
    pendingCells(grid).forEach(function (td) {
      var tr = td.closest("tr");
      if (!tr.classList.contains("deleting")) rows[tr.getAttribute("data-row-key")] = true;
    });
    n += Object.keys(rows).length;
    n += grid.querySelectorAll("tr.new-row").length;
    n += grid.querySelectorAll("tr.deleting").length;
    return n;
  }

  function refresh(grid) {
    var n = count(grid);
    grid.querySelector("[data-grid-count]").textContent = n ? n + " change" + (n === 1 ? "" : "s") + " waiting" : "";
    grid.querySelector("[data-grid-save]").disabled = !n;
    grid.querySelector("[data-grid-discard]").disabled = !n;
    grid.setAttribute("data-dirty", n ? "1" : "");
  }

  function message(grid, text) {
    var line = grid.querySelector("[data-grid-message]");
    line.textContent = text || ""; line.hidden = !text;
  }

  function paintCell(td, original) {
    var changed = td.hasAttribute("data-new") || td.hasAttribute("data-new-null");
    td.classList.toggle("edited", changed);
    td.classList.toggle("null", changed ? td.hasAttribute("data-new-null") : td.getAttribute("data-null") === "1");
    if (changed) {
      td.textContent = td.hasAttribute("data-new-null") ? "NULL" : td.getAttribute("data-new");
      td.title = "was: " + (td.getAttribute("data-null") === "1" ? "NULL" : original);
    } else {
      td.textContent = td.getAttribute("data-null") === "1" ? "NULL" : original;
      td.removeAttribute("title");
    }
  }

  // ---- editing one cell -------------------------------------------------------------------------------------------
  function edit(td) {
    var grid = gridOf(td), columns = info(grid).columns, column = columns[parseInt(td.getAttribute("data-col"), 10)];
    var tr = td.closest("tr");
    if (td.querySelector("input") || tr.classList.contains("deleting")) return;
    if (column.key || column.locked) { message(grid, column.key ? column.name + " is part of the primary key and cannot be edited here." : column.name + " is generated by the database."); return; }
    message(grid, "");
    var original = td.getAttribute("data-raw"), wasNull = td.getAttribute("data-null") === "1";
    var current = td.hasAttribute("data-new-null") ? null : td.hasAttribute("data-new") ? td.getAttribute("data-new") : (wasNull ? null : original);
    var input = el("input", {type: "text", "class": "cell-input", spellcheck: "false", autocomplete: "off"});
    input.value = current === null ? "" : current;
    var isNull = current === null;
    var nullButton = el("button", {type: "button", "class": "btn cell-null", title: "Set this cell to NULL", text: "NULL"});
    var done = false;

    function finish(save) {
      if (done) return;
      done = true;
      if (save) {
        var value = isNull ? null : input.value;
        var same = value === null ? wasNull : (!wasNull && value === original);
        td.removeAttribute("data-new"); td.removeAttribute("data-new-null");
        if (!same) { if (value === null) td.setAttribute("data-new-null", "1"); else td.setAttribute("data-new", value); }
      }
      paintCell(td, original);
      refresh(grid);
    }

    nullButton.addEventListener("mousedown", function (event) { event.preventDefault(); isNull = true; input.value = ""; finish(true); });
    input.addEventListener("input", function () { isNull = false; });
    input.addEventListener("keydown", function (event) {
      if (event.key === "Enter") { event.preventDefault(); finish(true); }
      else if (event.key === "Escape") { event.preventDefault(); event.stopPropagation(); finish(false); }
    });
    input.addEventListener("blur", function () { finish(true); });
    td.textContent = "";
    td.classList.remove("null");
    td.appendChild(input); td.appendChild(nullButton);
    input.focus(); input.select();
  }

  // ---- adding a row ---------------------------------------------------------------------------------------------
  function addRow(grid) {
    var columns = info(grid).columns, body = grid.querySelector("tbody");
    var empty = body.querySelector(".grid-empty");
    if (empty) empty.remove();
    var tr = el("tr", {"class": "new-row"});
    var remove = el("button", {type: "button", "class": "btn cell-null", "data-new-remove": "", title: "Remove this new row", text: "✕"});
    tr.appendChild(el("td", {"class": "grid-pick"}, [remove]));
    columns.forEach(function (column, index) {
      var input = el("input", {type: "text", "class": "cell-input", spellcheck: "false", autocomplete: "off", "data-new-col": String(index),
                               placeholder: column.locked ? "automatic" : column.default ? "default" : column.nullable ? "empty = NULL?" : "required"});
      if (column.locked) input.disabled = true;
      var nullButton = el("button", {type: "button", "class": "btn cell-null", "data-new-null-toggle": "", title: "Give this column the value NULL", text: "NULL"});
      if (column.locked) nullButton.hidden = true;
      tr.appendChild(el("td", {}, [input, nullButton]));
    });
    body.appendChild(tr);
    refresh(grid);
    var first = tr.querySelector("input:not([disabled])");
    if (first) first.focus();
  }

  // ---- saving ---------------------------------------------------------------------------------------------------
  function payload(grid) {
    var meta = info(grid), columns = meta.columns, edits = {}, order = [], inserts = [], deletes = [];
    pendingCells(grid).forEach(function (td) {
      var tr = td.closest("tr"), key = tr.getAttribute("data-row-key");
      if (tr.classList.contains("deleting")) return;
      if (!edits[key]) { edits[key] = {key: JSON.parse(key), old: {}, set: {}}; order.push(key); }
      var name = columns[parseInt(td.getAttribute("data-col"), 10)].name;
      edits[key].set[name] = cellValue(td);
      edits[key].old[name] = td.getAttribute("data-null") === "1" ? null : td.getAttribute("data-raw");
    });
    grid.querySelectorAll("tr.new-row").forEach(function (tr) {
      var row = {};
      tr.querySelectorAll("[data-new-col]").forEach(function (input) {
        var column = columns[parseInt(input.getAttribute("data-new-col"), 10)];
        if (input.hasAttribute("data-is-null")) row[column.name] = null;
        else if (input.value !== "") row[column.name] = input.value;
      });
      inserts.push(row);
    });
    grid.querySelectorAll("tr.deleting").forEach(function (tr) { deletes.push({key: JSON.parse(tr.getAttribute("data-row-key"))}); });
    return {schema: meta.schema, table: meta.table, edits: order.map(function (k) { return edits[k]; }), inserts: inserts, deletes: deletes};
  }

  function save(grid) {
    var holder = grid.closest("[data-structure]");
    if (!holder) return;
    var where = JSON.parse(holder.getAttribute("data-structure")), button = grid.querySelector("[data-grid-save]");
    button.disabled = true;
    message(grid, "");
    window.pgdasReview.start({
      server: where.server, db: where.db, rows: payload(grid),
      onError: function (text) { message(grid, text); },
      onSuccess: function (result) {
        toast(result.message || "Saved.");
        document.dispatchEvent(new CustomEvent("pgdas:changed", {detail: {server: where.server, redraw: true}}));
      },
    }).then(function () { refresh(grid); });
  }

  document.addEventListener("dblclick", function (event) {
    var td = event.target.closest("[data-grid] td[data-col]");
    if (td) edit(td);
  });

  document.addEventListener("change", function (event) {
    var pick = event.target.closest("[data-grid-pick]");
    if (!pick) return;
    var tr = pick.closest("tr");
    tr.classList.toggle("deleting", pick.checked);
    refresh(gridOf(pick));
  });

  document.addEventListener("click", function (event) {
    var guarded = event.target.closest("[data-grid] ~ .pager a, .tabs a");
    var dirtyGrid = document.querySelector("[data-grid][data-dirty='1']");
    if (guarded && dirtyGrid) {                                           // leaving the page would drop the waiting changes
      event.preventDefault(); event.stopPropagation();
      message(dirtyGrid, "Save or discard your changes first.");
      return;
    }
    var grid = event.target.closest("[data-grid]");
    if (!grid) return;
    if (event.target.closest("[data-grid-add]")) { addRow(grid); return; }
    if (event.target.closest("[data-grid-save]")) { save(grid); return; }
    if (event.target.closest("[data-grid-discard]")) {
      var holder = grid.closest("[data-structure]");
      document.dispatchEvent(new CustomEvent("pgdas:changed", {detail: {server: holder ? JSON.parse(holder.getAttribute("data-structure")).server : "", redraw: true}}));
      return;
    }
    var removeNew = event.target.closest("[data-new-remove]");
    if (removeNew) { removeNew.closest("tr").remove(); refresh(grid); return; }
    var toggle = event.target.closest("[data-new-null-toggle]");
    if (toggle) {
      var input = toggle.parentNode.querySelector("input"), on = !input.hasAttribute("data-is-null");
      if (on) { input.setAttribute("data-is-null", "1"); input.value = ""; input.disabled = true; } else { input.removeAttribute("data-is-null"); input.disabled = false; }
      toggle.classList.toggle("primary", on);
    }
  }, true);
})();
